create or replace function public.create_ingredient(p_name text, p_normalized_name text, p_aliases jsonb default '[]'::jsonb)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_ingredient_id bigint;
begin
  if not (select public.is_admin()) then
    raise exception using errcode = '42501', message = 'Administrator access required';
  end if;
  if exists (
    select 1 from public.ingredients i where i.normalized_name = p_normalized_name
    union all
    select 1 from public.ingredient_aliases a where a.normalized_alias = p_normalized_name
    union all
    select 1 from jsonb_to_recordset(coalesce(p_aliases, '[]'::jsonb)) as x(normalized_alias text)
      where x.normalized_alias = p_normalized_name
  ) then
    raise exception using errcode = '23505', message = 'Ingredient name or alias already exists';
  end if;
  if exists (
    select 1
    from jsonb_to_recordset(coalesce(p_aliases, '[]'::jsonb)) as x(alias text, normalized_alias text)
    where exists (select 1 from public.ingredients i where i.normalized_name = x.normalized_alias)
       or exists (select 1 from public.ingredient_aliases a where a.normalized_alias = x.normalized_alias)
  ) then
    raise exception using errcode = '23505', message = 'Ingredient name or alias already exists';
  end if;
  insert into public.ingredients (name, normalized_name)
  values (trim(p_name), p_normalized_name)
  returning id into v_ingredient_id;
  insert into public.ingredient_aliases (ingredient_id, alias, normalized_alias)
  select v_ingredient_id, trim(x.alias), x.normalized_alias
  from jsonb_to_recordset(coalesce(p_aliases, '[]'::jsonb)) as x(alias text, normalized_alias text);
  return v_ingredient_id;
end;
$$;

grant execute on function public.create_ingredient(text, text, jsonb) to authenticated;
revoke all on function public.create_ingredient(text, text, jsonb) from public;

